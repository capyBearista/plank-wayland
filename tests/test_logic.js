// Runs the actual QML JavaScript modules under Node; no display server required.
const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")
function load(file, names) {
    const source = fs.readFileSync(path.join(__dirname, "..", file), "utf8").replace(/^\.pragma library\s*/, "")
    return Function(source + "\nreturn {" + names.join(",") + "};")()
}
const I = load("services/AppIdentity.js", ["normalize","override","key","excluded","reorder"])
const C = load("services/Config.js", ["validateDock","validPins","validateStyles"])
const D = load("settings.js", ["dock","styles"])
assert.equal(I.normalize("Org.App.desktop"), "org.app")
assert.equal(I.key({appId:"obs"}), "com.obsproject.studio")
assert.equal(I.key({appId:"foo",desktopId:"org.foo.App"}), "org.foo.app")
assert.equal(I.key({appId:"FOO"},{foo:"org.bar.App"}), "org.bar.app")
assert.equal(I.excluded({appId:"XWaylandVideoBridge"},["xwaylandvideobridge"]), true)
assert.equal(I.key({appId:"foo",name:"Shared"}), "foo")
assert.equal(I.key({appId:"bar",name:"Shared"}), "bar")
const pins = [{appId:"a"},{appId:"b"},{appId:"c"}]
assert.deepEqual(I.reorder(pins,"a","c").map(p=>p.appId),["b","a","c"])
assert.deepEqual(I.reorder(pins,"a","").map(p=>p.appId),["b","c","a"])
assert.deepEqual(I.reorder(pins,"a","missing"),pins)
assert.deepEqual(pins.map(p=>p.appId),["a","b","c"])
const validated = C.validateDock(D.dock,{hideDelayMs:-50,iconSize:999,autoHide:"false",minimizeMode:"bogus",excludedApps:[1]})
assert.equal(validated.hideDelayMs,0)
assert.equal(validated.iconSize,96)
assert.equal(validated.autoHide,D.dock.autoHide)
assert.equal(validated.minimizeMode,"off")
assert.deepEqual(validated.excludedApps,D.dock.excludedApps)
assert.equal(C.validPins([{appId:"a",command:["x","--arg"]}]),true)
assert.equal(C.validPins([{appId:"a",command:{}}]),false)
assert.equal(C.validPins([{appId:""}]),false)
assert.equal(C.validateStyles(D.styles,{"clear-glass":{backgroundColor:"invalid"}})["clear-glass"].backgroundColor,D.styles["clear-glass"].backgroundColor)
console.log("Application identity, reordering, exclusions and configuration assertions passed.")
