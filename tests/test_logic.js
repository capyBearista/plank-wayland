// Runs the actual QML JavaScript modules under Node; no display server required.
const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")
function load(file, names) {
    const source = fs.readFileSync(path.join(__dirname, "..", file), "utf8").replace(/^\.pragma library\s*/, "")
    return Function(source + "\nreturn {" + names.join(",") + "};")()
}
const I = load("services/AppIdentity.js", ["normalize","override","key","excluded","reorder"])
const C = load("services/Config.js", ["validateDock","validPins","validateStyles"])
const D = load("settings.js", ["dock","styles"])
assert.equal(I.normalize("Org.App.desktop"), "org.app")
assert.equal(I.key({appId:"obs"}), "com.obsproject.studio")
assert.equal(I.key({appId:"foo",desktopId:"org.foo.App"}), "org.foo.app")
assert.equal(I.key({appId:"FOO"},{foo:"org.bar.App"}), "org.bar.app")
assert.equal(I.excluded({appId:"XWaylandVideoBridge"},["xwaylandvideobridge"]), true)
assert.equal(I.key({appId:"foo",name:"Shared"}), "foo")
assert.equal(I.key({appId:"foo",canonicalId:"old"},{foo:"new"}), "new")
assert.equal(I.normalize(I.override("constructor")), "constructor")
assert.equal(I.key({appId:"bar",name:"Shared"}), "bar")
const pins = [{appId:"a"},{appId:"b"},{appId:"c"}]
assert.deepEqual(I.reorder(pins,"a","c").map(p=>p.appId),["b","a","c"])
assert.deepEqual(I.reorder(pins,"a","").map(p=>p.appId),["b","c","a"])
assert.deepEqual(I.reorder(pins,"a","missing"),pins)
assert.deepEqual(pins.map(p=>p.appId),["a","b","c"])
const validated = C.validateDock(D.dock,{hideDelayMs:-50,iconSize:999,autoHide:"false",minimizeMode:"bogus",excludedApps:[1]})
assert.equal(validated.hideDelayMs,0)
assert.equal(validated.iconSize,96)
assert.equal(validated.autoHide,D.dock.autoHide)
assert.equal(validated.minimizeMode,"off")
assert.deepEqual(validated.excludedApps,D.dock.excludedApps)
assert.equal(C.validPins([{appId:"a",command:["x","--arg"]}]),true)
assert.equal(C.validPins([{appId:"a",command:{}}]),false)
assert.equal(C.validPins([{appId:""}]),false)
assert.equal(C.validateStyles(D.styles,{"clear-glass":{backgroundColor:"invalid"}})["clear-glass"].backgroundColor,D.styles["clear-glass"].backgroundColor)
console.log("Application identity, reordering, exclusions and configuration assertions passed.")

const W = load("services/WindowPolicy.js", ["addressOf","sameWorkspace","recoveryWorkspace","actionFor"])
assert.equal(W.addressOf({address:"ABCD"}),"0xabcd")
assert.equal(W.addressOf({lastIpcObject:{address:"0x1234"}}),"0x1234")
assert.equal(W.addressOf({address:"bad;command"}),"")
assert.equal(W.sameWorkspace({id:1,name:"1"},{id:1,name:"1"}),true)
assert.equal(W.sameWorkspace({id:2,name:"2"},{id:1,name:"1"}),false)
assert.equal(W.sameWorkspace(null,null),false)
assert.deepEqual(W.recoveryWorkspace("special:plank-minimized-3--eDP-1"),{id:3,monitor:"eDP-1"})
assert.equal(W.recoveryWorkspace("special:unrelated"),null)
const state = {mode:"workspace", current:true, numericWorkspace:true, hasHandle:true}
assert.equal(W.actionFor(state),"minimize-workspace")
assert.equal(W.actionFor({...state,current:false}),"focus")
assert.equal(W.actionFor({...state,protectedWindow:true}),"focus")
assert.equal(W.actionFor({...state,special:true}),"focus")
assert.equal(W.actionFor({...state,numericWorkspace:false}),"focus")
assert.equal(W.actionFor({...state,mode:"off"}),"focus")
assert.equal(W.actionFor({...state,mode:"native"}),"minimize-native")
assert.equal(W.actionFor({...state,current:false,minimized:true}),"restore-native")
assert.equal(W.actionFor({...state,mode:"off",recovery:{id:3}}),"restore-workspace")
console.log("Workspace-aware click policy assertions passed.")

const edit = load("services/Config.js", ["withOption"]).withOption
const initial = {...D.dock, zoomEnabled:false, zoomPercent:100}
const enabled = edit(D.dock,initial,"zoomEnabled",true)
assert.equal(enabled.zoomEnabled,true)
assert.equal(enabled.zoomPercent,150)
assert.equal(initial.zoomPercent,100)
assert.equal(edit(D.dock,enabled,"iconSize",48).iconSize,48)
assert.equal(edit(D.dock,enabled,"iconSize",200).iconSize,96)
assert.equal(edit(D.dock,enabled,"zoomPercent",100).zoomPercent,100)
assert.equal(edit(D.dock,enabled,"zoomEnabled",false).zoomEnabled,false)
assert.equal(edit(D.dock,enabled,"missing",true),enabled)
console.log("Reactive setting edit assertions passed.")
